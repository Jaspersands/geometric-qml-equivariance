def variance_with_error(samples: np.ndarray) -> Tuple[float, float]:
    """Unbiased sample variance and its standard error, √((m₄ − s⁴(n−3)/(n−1))/n)."""
    x = np.asarray(samples, dtype=float)
    n = x.size
    s2 = float(np.var(x, ddof=1))
    m4 = float(np.mean((x - x.mean()) ** 4))
    se = math.sqrt(max(m4 - s2 * s2 * (n - 3) / (n - 1), 0.0) / n)
    return s2, se


def circuit_for(kind: str, n_qubits: int, depth: int, couplings: Optional[Sequence[Tuple[int, int]]] = None):
    from .statevector import hardware_efficient_circuit, permutation_equivariant_circuit, su2_equivariant_circuit

    if kind == "su2":
        return su2_equivariant_circuit(n_qubits, depth, couplings)
    if kind == "hea":
        return hardware_efficient_circuit(n_qubits, depth)
    if kind == "sn":
        return permutation_equivariant_circuit(n_qubits, depth)
    raise ValueError(f"unknown ansatz kind {kind!r}")


def default_setup(kind: str, n_qubits: int) -> Tuple[np.ndarray, Operator, str]:
    """
    Input state and observable used in the study.

    * ``su2`` and ``hea``: singlet product state, O = open-chain Heisenberg Hamiltonian Σ σ_i·σ_{i+1}.
    * ``sn``: Néel state |0101…⟩, O = Σ_{i<j} X_iX_j (the observable of Schatzki et al.'s numerics).
      The singlet product state lies in the S = 0 isotypic block, where an S_N-symmetric
      circuit acts as a phase, so it gives zero variance; the chain Hamiltonian is not in i𝔤.
    """
    from .models import HeisenbergSpinChain, create_singlet_product_state_vector, pauli_string_sparse

    if kind in ("su2", "hea"):
        return (create_singlet_product_state_vector(n_qubits), HeisenbergSpinChain(n_qubits).get_sparse_matrix(),
                "singlet product, O = Σ σ_i·σ_{i+1} (open chain)")
    O = None
    for i in range(n_qubits):
        for j in range(i + 1, n_qubits):
            t = pauli_string_sparse({i: "X", j: "X"}, n_qubits)
            O = t if O is None else O + t
    return neel_state_vector(n_qubits), O.tocsr(), "Néel |0101…⟩, O = Σ_{i<j} X_iX_j"


def measure_loss_variance(kind: str, n_qubits: int, depth: int, n_samples: int = 2000, seed: int = 0,
                          psi0: Optional[np.ndarray] = None, obs: Optional[Operator] = None,
                          sector: bool = False) -> Dict[str, Any]:
    """
    Sample ℓ(θ) at uniformly random angles and return mean, variance and standard errors.
    ``sector=True`` runs an exchange circuit inside the S_z sector of ψ₀ (same angles, same values).
    """
    from .statevector import sample_losses

    if psi0 is None or obs is None:
        p, o, _ = default_setup(kind, n_qubits)
        psi0 = p if psi0 is None else psi0
        obs = o if obs is None else obs
    x = sample_losses(circuit_for(kind, n_qubits, depth), n_qubits, psi0, obs, n_samples, seed=seed, sector=sector)
    var, se = variance_with_error(x)
    return {"variance": var, "variance_se": se, "mean": float(x.mean()), "mean_se": float(x.std(ddof=1) / math.sqrt(x.size)),
            "n_samples": int(x.size), "depth": int(depth), "samples": x}


def compare_prediction(kind: str, n_qubits: int, depth: int, n_samples: int = 2000, seed: int = 0,
                       psi0: Optional[np.ndarray] = None, obs: Optional[Operator] = None) -> Dict[str, Any]:
    """Measured against predicted variance for one (ansatz, N, depth); z = (measured − predicted)/SE."""
    if psi0 is None or obs is None:
        p, o, _ = default_setup(kind, n_qubits)
        psi0 = p if psi0 is None else psi0
        obs = o if obs is None else obs
    pred = predict_loss(kind, n_qubits, psi0, obs)
    meas = measure_loss_variance(kind, n_qubits, depth, n_samples, seed, psi0, obs)
    # When the prediction is zero the measured variance is round-off (~1e−30), and so
    # is its standard error; their ratio means nothing. Compare both to the observable's
    # mean square instead and report z = 0 when both vanish at that scale.
    tiny = 1e-12 * _op_norm2(obs) / 2**n_qubits
    zero = pred["variance"] <= tiny and meas["variance"] <= tiny
    if zero or meas["variance_se"] <= 0:
        z = 0.0 if zero or meas["variance"] == pred["variance"] else math.inf
    else:
        z = (meas["variance"] - pred["variance"]) / meas["variance_se"]
    return {"zero_variance": bool(zero), "kind": kind, "n_qubits": n_qubits, "depth": depth, "predicted": pred["variance"],
            "predicted_mean": pred["mean"], "measured": meas["variance"], "measured_se": meas["variance_se"],
            "measured_mean": meas["mean"], "measured_mean_se": meas["mean_se"], "z": float(z),
            "dla_dimension": pred["dla_dimension"], "obs_in_algebra": pred["obs_in_algebra"],
            "n_samples": meas["n_samples"]}


def deep_depth(kind: str, n_qubits: int) -> int:
    """
    Depth used for the deep-circuit comparison: 4N layers for exchange and
    hardware-efficient circuits, 32 for the S_N circuit. In the depth scans
    (N = 6, 8, 10; L = 1, 2, 4, …, 64) the first depth within two standard errors
    of the prediction is 8, 16, 16 layers (hardware-efficient), 8, 16, 32 (exchange)
    and 8, 8, 8 (S_N): at most 3.2N for the first two.
    """
    return 32 if kind == "sn" else 4 * int(n_qubits)


def agreement(rows: Sequence[Dict[str, Any]]) -> Dict[str, float]:
    """χ² = Σ z² over the comparisons, its degrees of freedom and p-value, and max |z|."""
    from scipy.stats import chi2

    z = np.array([r["z"] for r in rows], dtype=float)
    c2 = float(np.sum(z**2))
    return {"chi2": c2, "dof": int(z.size), "p_value": float(chi2.sf(c2, z.size)), "max_abs_z": float(np.max(np.abs(z)))}


def variance_study(kinds: Sequence[str] = ("hea", "su2", "sn"), qubits: Sequence[int] = (4, 6, 8, 10, 12),
                   n_samples: int = 2000, seed: int = 0) -> Dict[str, Any]:
    """Predicted against measured loss variance at depth ``deep_depth`` for every (ansatz, N)."""
    rows = []
    for kind in kinds:
        for n in qubits:
            psi, O, label = default_setup(kind, n)
            r = compare_prediction(kind, n, deep_depth(kind, n), n_samples, seed + 1000 * n + {"hea": 1, "su2": 2, "sn": 3}[kind], psi, O)
            d = 2**n
            trO = _op_trace(O).real
            r["obs_scale"] = (_op_norm2(O) - trO**2 / d) / d          # ‖O − Tr O/d‖² / 2^N
            r["setup"] = label
            rows.append(r)
    return {"rows": rows, "agreement": agreement(rows), "n_samples": n_samples}


def depth_scan(kind: str, n_qubits: int, depths: Sequence[int] = (1, 2, 4, 8, 16, 32, 64), n_samples: int = 1000,
               seed: int = 0) -> Dict[str, Any]:
    """Measured variance against depth, with the deep-circuit prediction for comparison."""
    psi, O, label = default_setup(kind, n_qubits)
    pred = predict_loss(kind, n_qubits, psi, O)
    meas, se = [], []
    for L in depths:
        m = measure_loss_variance(kind, n_qubits, L, n_samples, seed + L, psi, O)
        meas.append(m["variance"])
        se.append(m["variance_se"])
    return {"kind": kind, "n_qubits": n_qubits, "depths": list(depths), "predicted": pred["variance"],
            "measured": meas, "measured_se": se, "setup": label}
