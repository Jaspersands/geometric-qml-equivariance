def neel_state_vector(n_qubits: int) -> np.ndarray:
    """|0101…⟩ (qubit 0 = most significant bit)."""
    n = int(n_qubits)
    b = sum(1 << (n - 1 - k) for k in range(1, n, 2))
    v = np.zeros(2**n, dtype=np.complex128)
    v[b] = 1.0
    return v


def _is_state_vector(x) -> bool:
    return not sp.issparse(x) and np.ndim(x) == 1


# --------------------------------------------------------------------------- #
# general path: decompose a DLA given by a dense basis
# --------------------------------------------------------------------------- #
def hermitian_basis(dla_basis: Sequence[np.ndarray]) -> List[np.ndarray]:
    """Hermitian orthonormal basis of i𝔤 from the anti-Hermitian basis returned by the closure."""
    out = []
    for a in dla_basis:
        b = -1j * np.asarray(a, dtype=np.complex128)
        b = 0.5 * (b + b.conj().T)
        out.append(b)
    M = np.stack([np.concatenate([b.real.ravel(), b.imag.ravel()]) for b in out], axis=1)
    Q, _ = np.linalg.qr(M)
    D = out[0].shape[0]
    res = []
    for k in range(Q.shape[1]):
        v = Q[: D * D, k] + 1j * Q[D * D:, k]
        res.append(v.reshape(D, D))
    return res


def _coefficients(basis_mat: np.ndarray, X: Operator) -> np.ndarray:
    """c_a = Tr[B_a X] for Hermitian B_a (rows of ``basis_mat`` are vec(B_a))."""
    Xd = X.toarray() if sp.issparse(X) else np.asarray(X)
    if Xd.ndim == 1:                                    # pure state |ψ⟩⟨ψ|
        Xd = np.outer(Xd, Xd.conj())
    # B Hermitian: Tr[B X] = Tr[B† X] = conj(vec B) · vec X
    return np.real(basis_mat @ Xd.ravel())


def _ad_matrix(basis_mat: np.ndarray, basis: Sequence[np.ndarray], Y: np.ndarray) -> np.ndarray:
    """(ad_Y)_{ba} = Tr[B_b · i[Y, B_a]] — a real antisymmetric matrix."""
    cols = []
    for B in basis:
        C = 1j * (Y @ B - B @ Y)
        cols.append(np.real(basis_mat @ C.ravel()))
    return np.stack(cols, axis=1)


def _orth(A: np.ndarray, tol: float) -> np.ndarray:
    if A.shape[1] == 0:
        return A
    q, r, _ = scipy.linalg.qr(A, mode="economic", pivoting=True)
    d = np.abs(np.diag(r))
    return q[:, : int(np.sum(d > tol * max(1.0, d[0] if len(d) else 0.0)))]


def reductive_decomposition(dla_basis: Sequence[np.ndarray], generators: Sequence[np.ndarray], seed: int = 0,
                            tol: float = 1e-8, max_tries: int = 10) -> Dict[str, Any]:
    """
    Split a compact (reductive) DLA into its centre and simple ideals.

    Parameters
    ----------
    dla_basis : the anti-Hermitian basis from ``DynamicalLieAlgebraAnalyzer`` (or any basis of 𝔤)
    generators : Hermitian gate generators (they generate 𝔤)

    Returns ``basis`` (Hermitian, orthonormal), ``center`` (d × c coefficient matrix with
    orthonormal columns) and ``ideals`` (list of d × d_j matrices).
    """
    basis = hermitian_basis(dla_basis)
    d = len(basis)
    Bm = np.stack([b.ravel() for b in basis], axis=0).conj()
    gens = []
    for g in generators:
        g = np.asarray(g, dtype=np.complex128)
        gens.append(g - np.trace(g) / g.shape[0] * np.eye(g.shape[0]))
    A = [_ad_matrix(Bm, basis, g) for g in gens]
    # centre: common kernel of ad_{G_k}
    stack = np.concatenate(A, axis=0)
    _, s, vt = np.linalg.svd(stack)
    scale = s[0] if len(s) else 1.0
    rank = int(np.sum(s > 1e-9 * scale))
    center = vt[rank:].T if rank < d else np.zeros((d, 0))
    Q_rem = vt[:rank].T
    rng = np.random.default_rng(seed)
    ideals: List[np.ndarray] = []
    while Q_rem.shape[1] > 0:
        for _ in range(max_tries):
            y = Q_rem @ rng.normal(size=Q_rem.shape[1])
            Y = sum(c * b for c, b in zip(y, basis))
            adY = _ad_matrix(Bm, basis, Y)
            K = Q_rem.T @ (adY.T @ adY) @ Q_rem
            w, V = np.linalg.eigh(K)
            # the top eigenvalue of −ad_y² is a root-pair (two-fold) inside a single ideal for generic y
            if len(w) < 3 or w[-3] < w[-1] * (1 - 1e-6):
                break
        x = Q_rem @ V[:, -1]
        I = (x / np.linalg.norm(x))[:, None]
        frontier = I
        while frontier.shape[1]:
            cand = np.concatenate([a @ frontier for a in A], axis=1)
            for _ in range(2):
                cand = cand - I @ (I.T @ cand)
            norms = np.linalg.norm(cand, axis=0)
            cand = cand[:, norms > tol]
            new = _orth(cand, tol) if cand.shape[1] else cand
            if new.shape[1]:
                new = new - I @ (I.T @ new)
                new, _ = np.linalg.qr(new)
            I = np.concatenate([I, new], axis=1)
            frontier = new
        ideals.append(I)
        R = Q_rem - I @ (I.T @ Q_rem)
        Q_rem = _orth(R, 1e-6)
    ideals.sort(key=lambda m: m.shape[1])
    return {"basis": basis, "basis_matrix": Bm, "center": center, "ideals": ideals,
            "ideal_dimensions": [m.shape[1] for m in ideals], "dimension": d}


def g_purities(X: Operator, decomposition: Dict[str, Any]) -> Dict[str, Any]:
    """𝔤-purities of an operator or pure state for a ``reductive_decomposition`` result."""
    c = _coefficients(decomposition["basis_matrix"], X)
    ideals = [float(np.sum((Q.T @ c) ** 2)) for Q in decomposition["ideals"]]
    center = float(np.sum((decomposition["center"].T @ c) ** 2))
    return {"ideals": ideals, "center": center, "total": float(np.sum(c**2)),
            "dimensions": list(decomposition["ideal_dimensions"])}


# --------------------------------------------------------------------------- #
# Schur–Weyl path
# --------------------------------------------------------------------------- #
class SchurBasis:
    """
    Isometries onto |S, M, a⟩ for N spin-½ (a labels a basis of the multiplicity space W_S).

    ``iso(S, M)`` returns (indices of the S_z = M sector, V) with V of shape
    (sector dim, m_S); columns for different M are related by the lowering
    operator, so ⟨S,M,a| X |S,M',a'⟩ = V_Mᵀ X[idx_M, idx_M'] V_M'.
    """

    def __init__(self, n_qubits: int):
        self.n = int(n_qubits)
        self.mult = spin_multiplicities(self.n)            # {S: m_S}
        self._hw = None
        self._cache: Dict[Tuple[float, float], Tuple[np.ndarray, np.ndarray]] = {}
        self._sector_idx: Dict[float, np.ndarray] = {}

    @property
    def spins(self) -> List[float]:
        return sorted(self.mult)

    def sector(self, M: float) -> np.ndarray:
        if M not in self._sector_idx:
            n_down = int(round(self.n / 2.0 - M))
            b = np.arange(2**self.n)
            pop = np.zeros_like(b)
            for q in range(self.n):
                pop += (b >> q) & 1
            self._sector_idx[M] = b[pop == n_down]
        return self._sector_idx[M]

    def _lowering(self, M: float) -> sp.csr_matrix:
        """S_− from the S_z = M sector to M − 1 (qubit value 0 = spin up)."""
        n = self.n
        src, dst = self.sector(M), self.sector(M - 1)
        pos = {int(b): i for i, b in enumerate(dst)}
        rows, cols = [], []
        for j, b in enumerate(src):
            b = int(b)
            for q in range(n):
                bit = 1 << (n - 1 - q)
                if not b & bit:
                    rows.append(pos[b | bit])
                    cols.append(j)
        return sp.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(len(dst), len(src)))

    def iso(self, S: float, M: float) -> Tuple[np.ndarray, np.ndarray]:
        key = (float(S), float(M))
        if key in self._cache:
            return self._cache[key]
        if abs(M) > S + 1e-9:
            raise ValueError(f"|M| = {abs(M)} exceeds S = {S}")
        if abs(M - S) < 1e-9:
            if self._hw is None:
                self._hw = _highest_weight_isometries(self.n)
            idx, V = self._hw[float(S)]
            out = (idx, np.real_if_close(V).astype(float))
        else:
            _, Vup = self.iso(S, M + 1)
            Mp = M + 1
            V = self._lowering(Mp) @ Vup / math.sqrt(S * (S + 1) - Mp * (Mp - 1))
            out = (self.sector(M), V)
        self._cache[key] = out
        return out

    def coefficients(self, psi: np.ndarray, S: float) -> np.ndarray:
        """C[M, a] = ⟨S, M, a|ψ⟩ for M = S, S−1, …, −S."""
        rows = []
        for k in range(int(round(2 * S)) + 1):
            idx, V = self.iso(S, S - k)
            rows.append(V.T @ psi[idx])
        return np.array(rows)

    def reduced(self, X, S: float, keep: str) -> np.ndarray:
        """
        Partial trace of Π_S X Π_S. ``keep='multiplicity'`` traces out the spin
        factor (an m_S × m_S matrix on W_S); ``keep='spin'`` traces out the
        multiplicity factor (a (2S+1) × (2S+1) matrix on V_S). ``X`` is a state
        vector or a (sparse) operator.
        """
        Ms = [S - k for k in range(int(round(2 * S)) + 1)]
        if _is_state_vector(X):
            C = self.coefficients(np.asarray(X), S)
            return C.T @ C.conj() if keep == "multiplicity" else C @ C.conj().T
        Xs = sp.csr_matrix(X) if not sp.issparse(X) else X.tocsr()
        isos = [self.iso(S, M) for M in Ms]
        if keep == "multiplicity":
            m = self.mult[float(S)]
            R = np.zeros((m, m), dtype=np.complex128)
            for idx, V in isos:
                R += V.T @ (Xs[idx][:, idx] @ V)
            return R
        R = np.zeros((len(Ms), len(Ms)), dtype=np.complex128)
        for i, (idx_i, Vi) in enumerate(isos):
            rows = Xs[idx_i]
            for j, (idx_j, Vj) in enumerate(isos):
                blk = rows[:, idx_j]
                if blk.nnz:
                    R[i, j] = np.sum(Vi * (blk @ Vj))
        return R

    def casimir_weights(self) -> Tuple[Dict[float, float], float]:
        """Traceless Casimir C̃ = Σ_S c_S Π_S: returns ({S: c_S}, Tr C̃²)."""
        dim = 2**self.n
        mean = sum(S * (S + 1) * (2 * S + 1) * m for S, m in self.mult.items()) / dim
        c = {S: S * (S + 1) - mean for S in self.mult}
        norm2 = sum(c[S] ** 2 * (2 * S + 1) * m for S, m in self.mult.items())
        return c, norm2


def _traceless_norm2(R: np.ndarray) -> float:
    d = R.shape[0]
    R0 = R - np.trace(R) / d * np.eye(d)
    return float(np.real(np.sum(np.abs(R0) ** 2)))


def schur_purities(X, n_qubits: int, symmetry: str = "su2", schur: Optional[SchurBasis] = None) -> Dict[str, Any]:
    """
    𝔤-purities per simple ideal (keyed by S) and of the centre.

    ``symmetry='su2'``: exchange-generated circuits, ideals su(m_S) on W_S (m_S ≥ 2).
    ``symmetry='sn'``: S_N-equivariant circuits, ideals su(2S+1) on V_S (2S+1 ≥ 2).
    """
    sb = schur if schur is not None else SchurBasis(n_qubits)
    ideals, dims = {}, {}
    traces = {}
    for S, m in sb.mult.items():
        d_spin = int(round(2 * S + 1))
        if symmetry == "su2":
            R = sb.reduced(X, S, keep="multiplicity")
            traces[S] = float(np.real(np.trace(R)))
            if m >= 2:
                ideals[S] = _traceless_norm2(R) / d_spin
                dims[S] = m * m - 1
        elif symmetry == "sn":
            R = sb.reduced(X, S, keep="spin")
            traces[S] = float(np.real(np.trace(R)))
            if d_spin >= 2:
                ideals[S] = _traceless_norm2(R) / m
                dims[S] = d_spin * d_spin - 1
        else:
            raise ValueError("symmetry must be 'su2' or 'sn'")
    c, norm2 = sb.casimir_weights()
    overlap = sum(c[S] * traces[S] for S in sb.mult)              # Tr[C̃ X]
    center = overlap**2 / norm2
    return {"ideals": ideals, "dimensions": dims, "center": center, "center_overlap": overlap,
            "center_norm2": norm2, "trace": sum(traces.values()), "total": sum(ideals.values()) + center}


def variance_from_purities(p_rho: Dict[str, Any], p_obs: Dict[str, Any]) -> float:
    """Σ_j P_j(ρ) P_j(O) / dim 𝔤_j for purity dicts from ``schur_purities`` or ``g_purities``."""
    if isinstance(p_rho["ideals"], dict):
        return float(sum(p_rho["ideals"][k] * p_obs["ideals"][k] / p_rho["dimensions"][k] for k in p_rho["ideals"]))
    return float(sum(a * b / d for a, b, d in zip(p_rho["ideals"], p_obs["ideals"], p_rho["dimensions"])))


def _op_trace(X) -> complex:
    if _is_state_vector(X):
        return float(np.vdot(X, X).real)
    return complex(X.diagonal().sum())


def _op_norm2(X) -> float:
    if sp.issparse(X):
        return float(np.real((X.multiply(X.conj())).sum()))
    return float(np.sum(np.abs(np.asarray(X)) ** 2))


def predict_loss(kind: str, n_qubits: int, psi0: np.ndarray, obs: Operator,
                 schur: Optional[SchurBasis] = None) -> Dict[str, Any]:
    """
    Predicted E[ℓ] and Var[ℓ] for a deep circuit of family ``kind``:

    * ``'hea'`` — 𝔤 = su(2^N)
    * ``'su2'`` — exchange gates with independent angles on a connected graph
    * ``'sn'``  — the S_N-equivariant generators ΣX, ΣY, Σ ZZ

    ``psi0`` is a pure input state, ``obs`` a Hermitian observable. For ``su2``
    and ``sn`` the formula requires O ∈ i𝔤 (or ρ ∈ i𝔤); ``obs_in_algebra``
    reports whether O's purities exhaust its traceless norm.
    """
    d = 2**n_qubits
    trO = _op_trace(obs).real
    obs_norm0 = _op_norm2(obs) - trO**2 / d                 # ‖O − Tr O/d‖²
    if kind == "hea":
        purity = 1.0 - 1.0 / d
        var = purity * obs_norm0 / (d * d - 1)
        return {"variance": var, "mean": trO / d, "obs_in_algebra": True, "dla_dimension": d * d - 1,
                "purities_rho": {"ideals": [purity]}, "purities_obs": {"ideals": [obs_norm0]}}
    sym = {"su2": "su2", "sn": "sn"}[kind]
    sb = schur if schur is not None else SchurBasis(n_qubits)
    pr = schur_purities(psi0, n_qubits, sym, sb)
    po = schur_purities(obs, n_qubits, sym, sb)
    mean = trO / d + pr["center_overlap"] * po["center_overlap"] / po["center_norm2"]
    dim = sum(po["dimensions"].values()) + 1
    return {"variance": variance_from_purities(pr, po), "mean": float(mean),
            "obs_in_algebra": bool(abs(po["total"] - obs_norm0) <= 1e-8 * max(1.0, obs_norm0)),
            "dla_dimension": dim, "purities_rho": pr, "purities_obs": po}


def _popcount(x: np.ndarray) -> np.ndarray:
    table = np.array([bin(k).count("1") for k in range(1 << 12)], dtype=np.int64)
    out = np.zeros(x.shape, dtype=np.int64)
    while np.any(x):
        out += table[x & 4095]
        x = x >> 12
    return out


def _sz_sector_moments(n: int, n_up: int, couplings: Sequence[Tuple[int, int, float]]) -> Tuple[float, float, int]:
    """
    Tr H and Tr H² inside the S_z sector with ``n_up`` up spins, for
    H = Σ J_ij σ_i·σ_j, without forming the matrix. On a basis state the diagonal is
    Σ J_ij s_i s_j (s = ±1); each anti-aligned pair (i, j) is flipped with amplitude
    2 J_ij, to a different state for each pair, so the row's squared norm is
    diag² + Σ_{anti-aligned} 4 J_ij².
    """
    x = np.arange(1 << n, dtype=np.int64)
    states = x[_popcount(x.copy()) == n_up]
    diag = np.zeros(states.size)
    off2 = np.zeros(states.size)
    for i, j, J in couplings:
        anti = ((states >> (n - 1 - i)) ^ (states >> (n - 1 - j))) & 1
        diag += J * (1.0 - 2.0 * anti)
        off2 += 4.0 * J * J * anti
    return float(diag.sum()), float(np.sum(diag * diag + off2)), int(states.size)


def singlet_input_prediction(n_qubits: int, couplings: Optional[Sequence] = None) -> Dict[str, Any]:
    """
    Deep exchange circuit with the singlet product input and O = H = Σ J_ij σ_i·σ_j
    (open chain by default): Var[ℓ] = Var_spec(H₀)/(C + 1), E[ℓ] = Tr H₀ / C, with H₀ the
    restriction of H to the S = 0 sector and C = C_{N/2} its dimension.

    For an SU(2)-invariant X, Tr_{S=0} X = Tr_{S_z=0} X − Tr_{S_z=1} X, because every
    spin multiplet with S ≥ 1 has one state in each of the two S_z sectors. Applied to
    H and H², this needs only the S_z sectors (C(N, N/2) states, 2.7 million at N = 24),
    not the Schur basis, so the prediction reaches beyond statevector sizes.
    ``obs_scale`` is Tr H²/2^N = 3 Σ J², the normalisation used in the figures.
    """
    n = int(n_qubits)
    if n % 2:
        raise ValueError("the singlet product input needs an even number of qubits")
    if couplings is None:
        couplings = [(i, i + 1) for i in range(n - 1)]
    cs = [(int(c[0]), int(c[1]), float(c[2]) if len(c) > 2 else 1.0) for c in couplings]
    t0, t0sq, d0 = _sz_sector_moments(n, n // 2, cs)
    t1, t1sq, d1 = _sz_sector_moments(n, n // 2 - 1, cs)
    C = d0 - d1
    tr, tr2 = t0 - t1, t0sq - t1sq
    mean = tr / C
    var_spec = tr2 / C - mean**2
    return {"variance": var_spec / (C + 1), "mean": mean, "singlet_dimension": C, "trace_H0": tr,
            "trace_H0_squared": tr2, "obs_scale": 3.0 * sum(J * J for _, _, J in cs)}


