"""
Loss variance of deep circuits predicted from the dynamical Lie algebra.

Theory
------
For a loss ℓ(θ) = Tr[U(θ) ρ U(θ)† O] and a circuit deep enough that U(θ) is
Haar distributed on the group G = e^𝔤 generated by its gates, Ragone et al.
(Nat. Commun. 15, 7172 (2024), Theorem 1) show that if O ∈ i𝔤 or ρ ∈ i𝔤 and
𝔤 = 𝔤₁ ⊕ … ⊕ 𝔤_{k−1} ⊕ 𝔷 (simple ideals plus centre), then

    E[ℓ]   = Tr[ρ_𝔷 O_𝔷]                       (+ Tr ρ · Tr O / d here, since 𝔤 is traceless)
    Var[ℓ] = Σ_j P_{𝔤_j}(ρ) P_{𝔤_j}(O) / dim 𝔤_j.

The 𝔤-purity P_𝔥(H) = Tr[H_𝔥²] is the squared Hilbert–Schmidt norm of the
orthogonal projection of H onto span_ℂ 𝔥 (⟨A, B⟩ = Tr A†B). With an orthonormal
Hermitian basis {B_a} of i𝔥, P_𝔥(H) = Σ_a Tr[B_a H]². The centre contributes
to the mean only. Fontana et al. (Nat. Commun. 15, 7171 (2024)) give the same
result through the adjoint representation. For 𝔤 = su(d) the formula is the
familiar Haar value (Tr ρ² − 1/d)(Tr O² − (Tr O)²/d)/(d² − 1).

Two ways to compute the purities
--------------------------------
* ``reductive_decomposition`` works from any dense DLA basis: it finds the centre
  (the kernel of ad) and splits the rest into simple ideals, each the ideal
  generated by an eigenvector of −ad_y² for a random y. Fine up to dim 𝔤 of a
  few hundred.
* ``SchurBasis`` uses Schur–Weyl duality, (ℂ²)^{⊗N} = ⊕_S V_S ⊗ W_S with V_S the
  spin-S irrep of SU(2) (dimension 2S+1) and W_S the S_N irrep (dimension m_S).
  - Exchange circuits (SU(2)-equivariant): 𝔤 = ⊕_S su(m_S) ⊗ 1_{V_S} ⊕ ℝ·C, so the
    simple ideals act on the multiplicity spaces W_S. With R_S = Tr_{V_S}(Π_S X Π_S),
    an m_S × m_S matrix, P_S(X) = ‖R_S − (Tr R_S / m_S) 1‖² / (2S+1).
  - S_N-equivariant circuits: 𝔤 = ⊕_S 1_{W_S} ⊗ su(2S+1) ⊕ ℝ·C (Kazi et al. 2024),
    so the ideals act on the spin spaces V_S. With R_S = Tr_{W_S}(Π_S X Π_S), a
    (2S+1) × (2S+1) matrix, P_S(X) = ‖R_S − (Tr R_S / (2S+1)) 1‖² / m_S.
  In both cases the centre is spanned by the traceless part of the Casimir C = S².
  The partial traces are taken in the basis |S, M, a⟩ built from highest-weight
  vectors and the lowering operator, so the cost is set by the S_z sectors
  (924 states at N = 12) rather than 4^N.

Limitations: the prediction is for the Haar ensemble on G, which a circuit with
independent uniformly random angles approaches only as its depth grows; the
measurement functions below show that convergence. It needs O ∈ i𝔤 or ρ ∈ i𝔤.
"""

